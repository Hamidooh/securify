export function generateExpressConfig(headersAudit: HeadersAudit): string {
  return `// Node.js (Express with Helmet)
import express from 'express';
import helmet from 'helmet';

const app = express();

app.disable('x-powered-by');

app.use(
  helmet({
    contentSecurityPolicy: {
      directives: {
        defaultSrc: ["'self'"],
        scriptSrc: ["'self'"],
        objectSrc: ["'none'"],
        upgradeInsecureRequests: [],
      },
    },
    hsts: {
      maxAge: 31536000,
      includeSubDomains: true,
      preload: true,
    },
  })
);`;
}
