import { HeadersAudit } from '../types';

export function generateNginxConfig(headersAudit: HeadersAudit): string {
  return `# Nginx Security Configuration
# Place inside your server {} or location / {} block

add_header X-Frame-Options "DENY" always;
add_header X-Content-Type-Options "nosniff" always;
add_header Referrer-Policy "strict-origin-when-cross-origin" always;
add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;
add_header Strict-Transport-Security "max-age=31536000; includeSubDomains; preload" always;
add_header Content-Security-Policy "default-src 'self'; img-src 'self' data: https:; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline';" always;

# Disable Server tokens disclosure
server_tokens off;`;
}

export function generateApacheConfig(headersAudit: HeadersAudit): string {
  return `# Apache (.htaccess or VirtualHost)
<IfModule mod_headers.c>
    Header always set X-Frame-Options "DENY"
    Header always set X-Content-Type-Options "nosniff"
    Header always set Referrer-Policy "strict-origin-when-cross-origin"
    Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
    Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains; preload"
    Header always set Content-Security-Policy "default-src 'self'; script-src 'self';"
    Header always unset X-Powered-By
</IfModule>

ServerSignature Off
ServerTokens Prod`;
}

export function generateCaddyConfig(headersAudit: HeadersAudit): string {
  return `# Caddyfile Security Headers
example.com {
    header {
        Strict-Transport-Security "max-age=31536000; includeSubDomains; preload"
        X-Content-Type-Options "nosniff"
        X-Frame-Options "DENY"
        Referrer-Policy "strict-origin-when-cross-origin"
        Permissions-Policy "camera=(), microphone=(), geolocation=()"
        Content-Security-Policy "default-src 'self';"
        -Server
    }
}`;
}

